// backend/scripts/gen-p4-bestiary.js
//
// Combines Task 1's LINES/RUNGS template, Task 2's deriveResistances/deriveLevelBand, and
// Task 3's pickDropItem into 288 generated creature rows (32 lines x 9 rungs) plus 288
// matching drop rows. Pure content generation: no live game code, no schema, no DB writes --
// the CLI entry point only writes a JS data file to disk. See
// docs/superpowers/plans/2026-08-08-p4-bestiary-generation.md, Task 4.
const fs = require('fs');
const path = require('path');
const { LINES, RUNGS } = require('./bestiary/template');
const { deriveResistances, deriveLevelBand } = require('./bestiary/derive');
const { pickDropItem } = require('./bestiary/dropMapping');

// Deterministic color per line, shade per rung -- every creature in a line shares a hue family,
// darker at higher rungs (bigger, tougher). Placeholder-quality; a later hand-polish pass is
// expected (see Task 6/7) before the umbrella considers art final.
function colorFor(lineIndex, rungIndex) {
  const hue = Math.round((lineIndex / 32) * 360);
  const lightness = 55 - rungIndex * 3; // higher rung = darker
  return hslToHex(hue, 55, Math.max(20, lightness));
}

function hslToHex(h, s, l) {
  s /= 100;
  l /= 100;
  const k = (n) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  const toHex = (x) => Math.round(255 * x).toString(16).padStart(2, '0');
  return `#${toHex(f(0))}${toHex(f(8))}${toHex(f(4))}`;
}

// One sentence per creature: rung supplies a size/skill word (Swarm -> tiny, Apex -> towering),
// the line supplies its element (if any) and name.
const SIZE_WORD = ['tiny', 'small', 'lean', 'armed', 'skilled', 'hulking', 'armoured', 'commanding', 'towering'];

function promptFor(line, rung) {
  const sizeWord = SIZE_WORD[rung.index];
  const elementWord = line.element ? `${line.element}-touched ` : '';
  // Styled here, not at generation time, so the prompt in the catalog says
  // what it will actually draw. See seeds/data/spritePrompt.js for why the
  // wording is what it is -- and for the two additions that were measured
  // making it worse.
  return styleEntityPrompt(`a ${sizeWord} ${elementWord}${line.name.toLowerCase()} creature`);
}

// SOMET-290. The rung normally decides behaviour (behavior_name below), but a
// handful of lowest-rung wildlife lines are the game's first SKITTISH
// creatures -- they flee rather than charge, and SOMET-289's starting-zone
// pens are built from them. Keyed by full name rather than by line or rung
// because it is these specific creatures, not every Swarm and not every
// Woodland.
const BEHAVIOR_OVERRIDES = {
  'Woodland Swarm': 'Skittish',
  'Beast Swarm': 'Skittish',
  'Highland Swarm': 'Skittish',
};

function generateBestiary() {
  const creatures = [];
  const drops = [];
  LINES.forEach((line, lineIndex) => {
    RUNGS.forEach((rung) => {
      const allFourPartial = line.name === 'Void' || line.name === 'Eldritch';
      const resistances = deriveResistances(rung.name, line.element, { allFourPartial });
      const band = deriveLevelBand(line.tier, rung.index);
      const name = `${line.name} ${rung.name}`;
      creatures.push({
        name,
        color: colorFor(lineIndex, rung.index),
        walkable: true,
        spawn_tiles: [],
        chance: 0.1,
        hp: rung.hp,
        max_hp: rung.hp,
        defense: rung.defense,
        resistances,
        prompt: promptFor(line, rung),
        level_min: band.min,
        level_max: band.max,
        behavior_name: BEHAVIOR_OVERRIDES[name] ?? rung.name, // resolved to a real behavior_id at seed time (Task 6)
      });
      const drop = pickDropItem(line.element, line.tier);
      drops.push({
        creature: name,
        item: drop.item,
        chance: drop.chance,
        min_qty: drop.min_qty,
        max_qty: drop.max_qty,
      });
    });
  });
  return { creatures, drops };
}

function writeOutput() {
  const { creatures, drops } = generateBestiary();
  const out = `// GENERATED by backend/scripts/gen-p4-bestiary.js -- do not hand-edit generated
// fields (color/prompt may be hand-polished after generation; everything else should be
// regenerated by re-running the script if the template/derive/dropMapping rules change).
// See docs/superpowers/plans/2026-08-08-p4-bestiary-generation.md.
const BESTIARY_P4_CREATURES = ${JSON.stringify(creatures, null, 2)};

const BESTIARY_P4_DROPS = ${JSON.stringify(drops, null, 2)};

module.exports = { BESTIARY_P4_CREATURES, BESTIARY_P4_DROPS };
`;
  fs.writeFileSync(path.join(__dirname, '../seeds/data/bestiaryP4.js'), out);
  console.log(`Wrote ${creatures.length} creatures, ${drops.length} drops.`);
}

module.exports = { generateBestiary, BEHAVIOR_OVERRIDES };
if (require.main === module) writeOutput();
